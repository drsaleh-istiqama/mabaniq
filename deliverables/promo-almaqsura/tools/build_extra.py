    p.image(str(f), x=12, y=28, w=118)
    p.mabaniq_mark(p.w - 12 - 14, 16, 12, text=False)
    p.image(str(SAMPLES / "almaqsura-logo.png"), x=p.w - 12 - 14 - 46 - 26, y=14, w=24)
    _multi(p, 138, 62, p.w - 150, TITLE, 24, True, WHITE, 13)
