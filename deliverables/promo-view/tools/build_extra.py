def build_brief_pdf(Guide, crop, out, TITLE, DATE_LINE, LIVE, SAMPLES):
    import build_guide as G
    p = Guide(landscape=True)
    p.live = LIVE
    p.set_margins(12, 12, 12)
    p.set_auto_page_break(auto=False)
    p.cover = True
    p.add_page()
    p.set_fill_color(*INK); p.rect(0, 0, p.w, p.h, style="F")
    p.set_fill_color(*GOLD); p.rect(0, p.h - 5, p.w, 5, style="F")
    f = crop(G.COVER_SHOT[0], 0.72, True)
    p.image(str(f), x=12, y=28, w=118)
    p.mabaniq_mark(p.w - 12 - 14, 16, 12, text=False)
    p.image(str(SAMPLES / "view-logo-light.png"), x=p.w - 12 - 14 - 46 - 26, y=12, w=24)
    _multi(p, 138, 58, p.w - 150, TITLE, 24, True, WHITE, 13)
    _multi(p, 138, p.get_y() + 2, p.w - 150, "الدليل المختصر — الميزات في نقاط على لقطات من المنصة ببيانات رؤية المنشورة", 13, False, GOLD, 8)
    _multi(p, 138, p.get_y() + 6, p.w - 150, f"{DATE_LINE}\nجدوى للدراسات والتطوير · الإصدار {G.VERSION} · {G.FOOT_NOTE}", 10, False, (200, 205, 215), 6)
    p.cover = False
    pages = brief_pages(G)
    for i, (sec, title, img, bullets) in enumerate(pages, 1):
        img = "report-portfolio-p1" if img == "REPORT_PREV" else img
        p.cover = True
        p.add_page()
        p.set_fill_color(*GOLD); p.rect(p.w - 12 - 3, 12, 3, 20, style="F")
        _txt(p, 12, 12, p.w - 24 - 6, 11, sec, 20, True)
        _txt(p, 12, 23, p.w - 24 - 6, 7, title, 11, False, MUTED)
        tw = 92
        box_w = p.w - 24 - tw - 8
        box_h = p.h - 40 - 14
        f = crop(img, 0.66, True)
        im = Image.open(f); iw, ih = im.size
        w = box_w; h = w * ih / iw
        if h > box_h:
            h = box_h; w = h * iw / ih
        x = 12 + (box_w - w) / 2
        p.set_draw_color(*LINE); p.set_line_width(0.3); p.rect(x - 0.5, 40 - 0.5, w + 1, h + 1)
        p.image(str(f), x=x, y=40, w=w, h=h)
