"""إنفوجرافيك «المنصة في صفحة واحدة» (يُدرج بعد الغلاف) + الدليل المختصر (لقطات + نقاط) — نسخة بيانات رؤية العقارية المنشورة.
يُستورد من build_guide.py. كل الرسوم أشكال fpdf2 ونصوص مركَّبة برمجيًا — لا صور مولَّدة، والأرقام من demo-state.json."""
from __future__ import annotations

from fpdf.enums import XPos, YPos
from PIL import Image

INK = (23, 32, 48)
GOLD = (26, 111, 90)
MUTED = (110, 120, 135)
LINE = (214, 218, 226)
PALE = (247, 248, 250)
GREEN = (18, 78, 66)
NAVY2 = (18, 78, 66)
WHITE = (255, 255, 255)


def _txt(p, x, y, w, h, t, size=9, bold=False, color=INK, align="R"):
    p.set_font("Tajawal", "B" if bold else "", size)
    p.set_text_color(*color)
    p.set_xy(x, y)
    p.cell(w, h, t, align=align)


def _multi(p, x, y, w, t, size=8.5, bold=False, color=INK, lh=None, align="R"):
    p.set_font("Tajawal", "B" if bold else "", size)
    p.set_text_color(*color)
    p.set_xy(x, y)
    p.multi_cell(w, lh or size * 0.52, t, align=align, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    return p.get_y()


def _box(p, x, y, w, h, fill=PALE, r=2.5, stroke=None):
    p.set_fill_color(*fill)
    if stroke:
        p.set_draw_color(*stroke)
        p.set_line_width(0.3)
        p.rect(x, y, w, h, style="FD", round_corners=True, corner_radius=r)
    else:
        p.rect(x, y, w, h, style="F", round_corners=True, corner_radius=r)


def _circle(p, cx, cy, d, fill=GOLD, label=None, size=9, color=INK):
    p.set_fill_color(*fill)
    p.ellipse(cx - d / 2, cy - d / 2, d, d, style="F")
    if label:
        _txt(p, cx - d / 2, cy - d / 2, d, d, label, size, True, color, "C")


